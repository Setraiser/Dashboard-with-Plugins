/** Этап жизненного цикла одного запуска игры. */
export type GameStatus = "ready" | "playing" | "over";

/** Тип фигуры определяет, как клик влияет на счёт и здоровье игрока. */
export type FallingObjectKind = "target" | "decoy";

/** Игровая фигура в нормализованных координатах игрового поля. */
export interface FallingObject {
  /** Уникальный в рамках запуска идентификатор, используемый для клика и рендера. */
  id: number;
  kind: FallingObjectKind;
  /** Положение по горизонтали в диапазоне, близком к [0, 1]. */
  x: number;
  /** Положение по вертикали; значение около 1 соответствует нижней границе поля. */
  y: number;
  /** Скорость падения в высотах поля за секунду. */
  speed: number;
}

/** Полное состояние симуляции; функции модели возвращают его неизменяемые обновления. */
export interface GameState {
  status: GameStatus;
  /** Время с начала игры в миллисекундах. */
  elapsedMs: number;
  score: number;
  health: number;
  objects: FallingObject[];
  /** Следующий идентификатор для создаваемой фигуры. */
  nextObjectId: number;
  /** Время появления следующей фигуры относительно начала игры, в миллисекундах. */
  nextSpawnAtMs: number;
}
